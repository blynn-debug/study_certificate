REVIEWS = []


def reviewed(item_id, answer, prompt, claims, note, *, finding="", kind="text",
             derivation="", assumptions=""):
    """Record a specific read question; never approve a topic automatically."""
    REVIEWS.append({
        "id": item_id, "answer": answer, "clean_prompt": prompt,
        "claim_ids": claims.split(), "review_note": note,
        "source_finding": finding, "answer_kind": kind,
        "concept_review": {
            "derivation": derivation, "assumptions": assumptions,
            "basis": "explicit_conditions_and_independent_reasoning",
            "current_law_claim": False,
        } if derivation else None,
    })


def mc(item_id, answer, prompt, claims, note, *, finding=""):
    """Declare a reviewed question with four visible, unambiguous choices."""
    reviewed(item_id, answer, prompt, claims, note, finding=finding,
             kind="multiple_choice")


def concept(item_id, answer, prompt, derivation, assumptions, *, finding="",
            kind="multiple_choice", claims=""):
    """Require an individual proof; no inference from topic or official-source presence."""
    reviewed(item_id, answer, prompt, claims, derivation, finding=finding,
             kind=kind, derivation=derivation, assumptions=assumptions)


