def main() -> None:
    """Update manual recoveries and chapter review records idempotently."""
    path = ROOT / "answer_overrides.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    packets = {p["id"]: p for p in json.loads((ROOT / "answer_packets.json").read_text(encoding="utf-8"))["items"]}
    for qid, (answer, page, explanation) in RECOVERIES.items():
        answer_pages = page if isinstance(page, list) else [page]
        record = data.setdefault(qid, {})
        record.update({
            "publisher_answer": answer,
            "explanation_text": explanation,
            "explanation_representation": "reviewer_paraphrase_of_publisher_explanation",
            "answer_pages": answer_pages,
            "source_pages": sorted({packets[qid]["question_page"], *answer_pages}),
            "key_review": "intended_answer_recovered_from_original_explanation; not_independent_gold_validation",
            "locator_status": "manual_source_recovery",
        })
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    log_path = ROOT / "review_log.json"
    log = json.loads(log_path.read_text(encoding="utf-8"))
    log["chapters"].update(CHAPTER_FINDINGS)
    log_path.write_text(json.dumps(log, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    progress_path = ROOT / "progress.json"
    progress = json.loads(progress_path.read_text(encoding="utf-8"))
    progress["answer_review"]["reviewed_ids"] = [
        qid for qid, packet in packets.items() if packet["chapter_id"] in log["chapters"]
    ]
    progress["answer_review"]["review_log"] = "review_log.json"
    progress["answer_review"]["meaning"] = "해설을 EVAL 설계에 사용하기 위한 검토. 정답의 독립 검증이나 최신 법령 전수검증이 아니다."
    progress_path.write_text(json.dumps(progress, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(RECOVERIES)} manual source recoveries saved.")


if __name__ == "__main__":
    main()
