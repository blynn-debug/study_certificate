def main():
    """Merge only the specific reviewed records, preserving other review work."""
    path = ROOT / "item_releases.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    packets = {
        x["id"]: x for x in json.loads(
            (ROOT.parent / "eval/answer_packets.json").read_text(encoding="utf-8")
        )["items"]
    }
    claims = {x["id"] for x in json.loads((ROOT / "verified_claims.json").read_text(encoding="utf-8"))["items"]}
    for review in ITEMS:
        item_id = review["id"]
        packet = packets[item_id]
        assert set(review["claim_ids"]) <= claims, item_id
        data["items"][item_id] = {
            "state": "adjudicated_current", "as_of": "2026-10-13",
            "answer": review["answer"], "answer_kind": "free_response" if packet["kind"] == "warmup" else "choice",
            "prompt_correspondence_reviewed": True,
            "clean_prompt": review["clean_prompt"],
            "evidence": [f"{packet['document']}:{packet['question_page']}", *review["claim_ids"]],
            "review_note": review["review_note"],
            "original_publisher_answer": packet["publisher_answer"],
            "scope": "This reviewed prompt and answer; not approval of every sentence on the source page.",
        }
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Recorded {len(ITEMS)} individual tax item reviews.")


if __name__ == "__main__":
    main()
