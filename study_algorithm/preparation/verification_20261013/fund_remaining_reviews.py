REVIEWS = []


def mc(item_id, answer, prompt, claims, note, *, finding=""):
    """Record only the explicitly reviewed learner prompt."""
    REVIEWS.append({
        "id": item_id, "answer": answer, "clean_prompt": prompt,
        "claim_ids": claims.split(), "review_note": note,
        "source_finding": finding, "answer_kind": "multiple_choice",
    })


def concept(item_id, answer, prompt, derivation, assumptions, *, finding="", claims=""):
    """Require explicit reasoning and scope for a stable conceptual question."""
    mc(item_id, answer, prompt, claims, derivation, finding=finding)
    REVIEWS[-1]["concept_review"] = {
        "derivation": derivation, "assumptions": assumptions,
        "basis": "explicit_conditions_and_independent_reasoning",
        "current_law_claim": False,
    }


def reviewed(item_id, answer, prompt, claims, note, *, finding="", kind="text"):
    """Record a checked short answer without inventing multiple-choice options."""
    mc(item_id, answer, prompt, claims, note, finding=finding)
    REVIEWS[-1]["answer_kind"] = kind


def concept_note(item_id, answer, prompt, derivation, assumptions, *, finding="", kind="text", claims=""):
    """Keep independent reasoning for a short conceptual answer."""
    concept(item_id, answer, prompt, derivation, assumptions, finding=finding, claims=claims)
    REVIEWS[-1]["answer_kind"] = kind


