def main():
    """Bind each repaired variant to the exact source corrections actually reviewed."""
    def read(path):
        return json.loads(path.read_text(encoding="utf-8"))

    data = read(ROOT / "item_releases.json")
    packets = {x["id"]: x for x in read(ROOT.parent / "eval/answer_packets.json")["items"]}
    claims = {x["id"]: x for x in read(ROOT / "verified_claims.json")["items"]}
    corrections = read(ROOT / "source_corrections.json")["items"]
    if len(ITEMS) != len({x["id"] for x in ITEMS}):
        raise ValueError("Duplicate repaired item")
    for review in ITEMS:
        packet = packets[review["id"]]
        matched = [x for x in corrections if review["id"] in x["item_ids"]]
        if not matched or not set(review["claim_ids"]) <= set(claims):
            raise ValueError(f"Missing correction or verified evidence: {review['id']}")
        release = {
            "state": "adjudicated_current", "as_of": "2026-10-13",
            "prompt_variant": "corrected_reviewed_prompt", "answer": review["answer"],
            "answer_kind": review["answer_kind"], "clean_prompt": review["clean_prompt"],
            "prompt_correspondence_reviewed": True,
            "evidence": [f"{packet['document']}:{packet['question_page']}", *review["claim_ids"]],
            "review_note": review["review_note"], "original_publisher_answer": packet["publisher_answer"],
            "scope": "The explicitly rewritten prompt only. Never regrade an original-prompt attempt with this key.",
            "correction_resolution": {
                row["id"]: {"reviewed_correction_sha256": fingerprint(row),
                            "resolution_note": review["review_note"]} for row in matched
            },
        }
        release["corrected_variant_sha256"] = variant_fingerprint(release)
        if not is_current_release(release, matched):
            raise ValueError("Invalid repaired release")
        data["items"][review["id"]] = release
    (ROOT / "item_releases.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Recorded {len(ITEMS)} individually reviewed corrected prompts; original defects preserved.")


if __name__ == "__main__":
    main()
